  <h1>Aide</h1>
  <p>Cette page explique à quoi sert chaque page du site et comment faire une demande de réservation.</p>

  <hr>

  <h2>1. À quoi sert chaque page ?</h2>
  <ul>
    <li><strong>Accueil :</strong> présente le site et propose un moteur de recherche pour trouver rapidement un hébergement disponible sur des dates précises (arrivée, départ, nombre d'adultes et d'enfants).</li>
    <li><strong>Hébergements :</strong> liste tous les hébergements proposés, avec une recherche par nom. Cliquez sur un hébergement pour accéder à sa fiche détaillée (photos, description, équipements, tarifs).</li>
    <li><strong>Calendrier :</strong> affiche en un seul tableau les disponibilités et tarifs de tous les hébergements sur plusieurs mois. Il permet aussi de réserver plusieurs biens en une seule demande.</li>
    <li><strong>Fiche d'un hébergement :</strong> détaille un hébergement (photos, description, équipements) et propose un onglet « Tarifs et disponibilités » pour choisir des dates et envoyer une demande de réservation.</li>
    <li><strong>Contact :</strong> permet de nous écrire directement pour toute question ou demande particulière.</li>
    <li><strong>Politique de confidentialité :</strong> explique comment vos données personnelles sont collectées et utilisées.</li>
  </ul>

  <hr>

  <h2>2. Comment faire une demande de réservation ?</h2>
  <p>Il existe trois façons d'envoyer une demande de réservation, toutes gratuites et sans engagement :</p>

  <h3>a. Depuis la recherche de la page d'accueil</h3>
  <ol>
    <li>Sur la page d'accueil, renseignez la date d'arrivée, la date de départ et le nombre de voyageurs (adultes, enfants).</li>
    <li>Cliquez sur « Rechercher » : la liste des hébergements disponibles pour ces dates s'affiche.</li>
    <li>Cliquez sur l'hébergement souhaité, puis complétez le formulaire de demande de réservation (nom, email, téléphone, message) et validez.</li>
  </ol>

  <h3>b. Depuis le calendrier</h3>
  <ol>
    <li>Ouvrez la page « Calendrier ».</li>
    <li>Renseignez le formulaire avec les dates souhaitées et le nombre de personnes, puis cliquez sur « Afficher les disponibilités ». Choisissez des dates plus larges afin d'avoir une meilleure visibilité sur les jours avant et après vos dates.</li>
    <li>Cliquez sur la date d'arrivée souhaitée pour un hébergement, puis sur la date de départ, directement dans le tableau. Vous pouvez répéter l'opération sur un autre hébergement (mêmes dates ou dates différentes) pour l'ajouter à votre sélection et réserver plusieurs biens à la fois.</li>
    <li>Validez votre sélection puis complétez le formulaire pour envoyer votre demande.</li>
  </ol>
  <p><em>À savoir : vous pouvez sélectionner plusieurs biens afin d'avoir suffisamment de place pour le nombre de voyageurs, et vous pouvez aussi sélectionner un bien puis en changer en sélectionnant de nouvelles dates dans le tableau.</em></p>

  <h3>c. Depuis l'onglet « Tarifs et disponibilités » d'un hébergement</h3>
  <ol>
    <li>Ouvrez la fiche de l'hébergement qui vous intéresse.</li>
    <li>Choisissez l'onglet « Tarifs et disponibilités ».</li>
    <li>Sélectionnez vos dates d'arrivée et de départ ainsi que le nombre de voyageurs pour afficher le tarif correspondant.</li>
    <li>Complétez le formulaire de demande (nom, email, téléphone, message) et validez.</li>
  </ol>

  <p>Dans tous les cas, votre demande est ensuite transmise au partenaire concerné, qui vous recontactera pour confirmer la réservation.</p>

  <p><em>Une question qui n'est pas couverte ici ? <a href="/contact">Contactez-nous</a>.</em></p>
